HOST = "testserver"


class SwapCase(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.world = build_world()

    def tearDown(self):
        state.end()

    def user(self, who):
        return self.world.users[who] if isinstance(who, str) else who

    def api(self, who):
        client = APIClient(HTTP_HOST=HOST)
        client.force_authenticate(self.user(who))
        return client

    def signed_in(self, who):
        """Through the real sign-in path (the HttpOnly session cookie, P1-T4a); use inside
        ``identity.fake_keycloak()``."""
        with schema_context("public"):
            hospital = Hospital.objects.get(schema_name=TEST_SCHEMA)
        return identity.staff_client(hospital, HOST, self.user(who))

    def other_patient(self, department=None, **fields):
        """A second patient with clinical data; with ``department``, an open inpatient visit
        filed under it (and only it)."""
        w = self.world
        values = {
            "name": f"Bharat Other {CANARY[-4:]}",
            "gender": "male",
            "phone_number": "+919812345678",
            "address": "3 Station Road, Nagpur",
            "pincode": 440001,
            "year_of_birth": 1975,
            "blood_group": "O_negative",
            "geo_organization": w.patient.geo_organization,
            "extensions": {"core": {"note": CANARY}},
        }
        values.update(fields)
        patient = Patient.objects.create(**values)
        encounter = None
        if department is not None:
            encounter = Encounter.objects.create(
                patient=patient,
                facility=w.facility,
                status="in_progress",
                encounter_class="imp",
                priority="routine",
                period={"start": timezone.now().isoformat()},
                discharge_summary_advice=f"advice {CANARY}",
                hospitalization={"admit_source": "outp", "diet_preference": "vegan"},
            )
            EncounterOrganization.objects.create(
                encounter=encounter, organization=w.departments[department]
            )
            encounter.save()
        return patient, encounter

    def govt(self, name, parent=None):
        return Organization.objects.create(name=name, org_type="govt", parent=parent)


def registration_body(got, **changes):
    """The body CARE's web app sends to save a patient (PatientRegistration.tsx: ``form.reset``
    from the GET, then ``onSubmit``), rebuilt from what the GET returned."""
    dob = got.get("date_of_birth")
    age = None if dob else timezone.localdate().year - int(got["year_of_birth"])
    identifiers = [
        {"config": i["config"]["id"], "value": i["value"]}
        for i in got.get("instance_identifiers") or []
        if i.get("value")
    ]
    body = {
        "name": got["name"],
        "phone_number": got["phone_number"],
        "emergency_phone_number": got.get("emergency_phone_number")
        or got["phone_number"],
        "emergency_phone_number_same_as_phone_number": not got.get(
            "emergency_phone_number"
        ),
        "gender": got["gender"],
        "age_or_dob": "dob" if dob else "age",
        "tags": [],  # "only used for create patient", sent anyway
        "address": got.get("address") or "",
        "permanent_address": got.get("permanent_address") or got.get("address") or "",
        "permanent_address_same_as_address": not got.get("permanent_address"),
        "geo_organization": (got.get("geo_organization") or {}).get("id", ""),
        "pincode": got.get("pincode"),
        "is_deceased": bool(got.get("deceased_datetime")),
        "deceased_datetime": got.get("deceased_datetime"),
        "required_identifiers": [],
        "optional_identifiers": identifiers,
        "autogenerated_identifiers": [],
        "_selected_levels": [got.get("geo_organization")],
        "identifiers": identifiers,
        # ext.defaults merged with the GET's (projected: empty) extensions
        "extensions": dict(got.get("extensions") or {}),
    }
    if dob:
        body["date_of_birth"] = dob
    else:
        body["age"] = age
    if got.get("blood_group"):  # `data.blood_group || undefined`
        body["blood_group"] = got["blood_group"]
    body.update(changes)
    return body

#!/usr/bin/env bash
# Run upstream CARE locally with the IndieHR low-memory override (P0-T5), in tenant mode with
# two synthetic demo hospitals at http://alpha.localhost:8080 and http://beta.localhost:8080
# (P1-T2b), and Keycloak on demand (P1-T3: `scripts/care-dev.sh keycloak help`).
# Usage: scripts/care-dev.sh <up|down|ps|logs|seed|reset-passwords|frontend|shell|keycloak|provision|provision-demo|audit-anchors>
set -euo pipefail
ROOT="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
BACKEND="$ROOT/apps/backend"
COMPOSE=(docker compose --project-directory "$BACKEND" -p indiehr-care
  -f "$BACKEND/docker-compose.yaml" -f "$BACKEND/docker-compose.local.yaml"
  -f "$ROOT/deploy/dev/care-local.override.yaml" -f "$ROOT/deploy/dev/keycloak.override.yaml")
FE_IMAGE=indiehr-frontend:local
DB=ihr_dev
HOSPITALS=(alpha beta)
new_password_raw() { python3 -c 'import secrets;print(secrets.token_urlsafe(18))'; }
KC_ENV="$ROOT/deploy/dev/keycloak.env"

# Keycloak's dev secrets: generated once, git-ignored, owner-only (P1-T3).
if [[ ! -f "$KC_ENV" ]]; then
  (umask 077; {
    echo "# Local Keycloak secrets (P1-T3), generated by scripts/care-dev.sh. Never commit."
    echo "KC_DB_PASSWORD=$(python3 -c 'import secrets;print(secrets.token_hex(16))')"
    echo "KC_BOOTSTRAP_ADMIN_USERNAME=ihr-admin"
    echo "KC_BOOTSTRAP_ADMIN_PASSWORD=$(new_password_raw)"
    echo "KC_BOOTSTRAP_ADMIN_CLIENT_ID=ihr-bootstrap"
    echo "KC_BOOTSTRAP_ADMIN_CLIENT_SECRET=$(python3 -c 'import secrets;print(secrets.token_hex(24))')"
  } > "$KC_ENV")
fi

new_password() { echo "Ihr-$(python3 -c 'import secrets;print(secrets.token_urlsafe(9))')-7"; }

# seed_hospital <slug> [--passwords-only]: prints "<slug> <password>"
seed_hospital() {
  local pw; pw="$(new_password)"
  "${COMPOSE[@]}" exec -T -e TEST_PASSWORD="$pw" backend \
    python manage.py ihr_seed_demo --slug "$1" "${@:2}" | tail -1 >&2
  echo "$1 $pw"
}

# write_test_users "alpha <pw>" "beta <pw>"
write_test_users() {
  mkdir -p "$ROOT/deploy/seed"
  # Keep the Keycloak section (written by `keycloak seed`) when the CARE logins are rewritten.
  local kc=""
  [[ -f "$ROOT/deploy/seed/TEST_USERS.md" ]] &&
    kc="$(sed -n -e '/<!-- keycloak:start -->/,/<!-- keycloak:end -->/p' \
      -e '/<!-- provisioned:start -->/,/<!-- provisioned:end -->/p' "$ROOT/deploy/seed/TEST_USERS.md")"
  {
    cat <<EOT
# Local test users — synthetic, localhost only, NOT committed

Generated $(date '+%d-%m-%Y %H:%M') by \`scripts/care-dev.sh\`. CARE's public fixture passwords were replaced.
Each demo hospital is a separate tenant with its own users: the same username exists in both,
with a **different password** in each.

EOT
    for entry in "$@"; do
      read -r slug pw <<<"$entry"
      cat <<EOT
## ${slug^} — http://$slug.localhost:8080

**Password for every user below:** \`$pw\`

EOT
    done
    cat <<'EOT'
| Username | CARE role | Use it for |
|---|---|---|
| care-doctor | Doctor | OPD/IPD consultations, prescriptions, orders |
| care-nurse | Nurse | Vitals, medication administration, nursing notes |
| care-pharmacist | Pharmacist | Dispensing, stock |
| care-billing | Staff | Charges, invoices, payments (cannot create billing accounts; see GAP_ANALYSIS) |
| care-staff | Staff | Front desk / registration |
| care-fac-admin | Facility Admin | Facility settings, billing accounts, tariffs, users |
| care-admin | Administrator | Organisation-level admin |
| care-volunteer | Volunteer | Read-mostly |
| admin | Superuser | Not for the web app |
EOT
    if [[ -n "$kc" ]]; then printf '\n%s\n' "$kc"; fi
  } > "$ROOT/deploy/seed/TEST_USERS.md"
  chmod 600 "$ROOT/deploy/seed/TEST_USERS.md"
}

# Run a Keycloak management command in the backend container. The admin secret is passed by
# name only (-e VAR), so it never shows in the host's process list, and it is never part of the
# backend's own environment.
kc_manage() {
  set -a
  # shellcheck disable=SC1090,SC1091
  source "$KC_ENV"
  set +a
  IHR_KEYCLOAK_ADMIN_CLIENT_ID="$KC_BOOTSTRAP_ADMIN_CLIENT_ID" \
  IHR_KEYCLOAK_ADMIN_CLIENT_SECRET="$KC_BOOTSTRAP_ADMIN_CLIENT_SECRET" \
    "${COMPOSE[@]}" exec -T -e IHR_KEYCLOAK_ADMIN_CLIENT_ID -e IHR_KEYCLOAK_ADMIN_CLIENT_SECRET \
    backend python manage.py "$@"
}

# One worker's narrow Keycloak secret into its own git-ignored env file (P1-T5f).
write_worker_env() {
  local secret
  secret="$(kc_manage ihr_keycloak_service_secret "$1" | tail -1)"
  [[ -n "$secret" ]] || { echo "no secret for the $1 worker" >&2; exit 1; }
  (umask 077; printf '%s=%s\n' "$3" "$secret" > "$ROOT/deploy/dev/$2"; chmod 600 "$ROOT/deploy/dev/$2")
}

keycloak_cmd() {
  case "${1:-help}" in
    up)
      # Own database and owner role on the dev Postgres (never ihr_dev); password from keycloak.env
      "${COMPOSE[@]}" up -d --wait db
      set -a
      # shellcheck disable=SC1090,SC1091
      source "$KC_ENV"
      set +a
      # The password reaches psql through the environment, never the command line.
      "${COMPOSE[@]}" exec -T -e KC_DB_PASSWORD db psql -U postgres -v ON_ERROR_STOP=1 -q <<'SQL'
\getenv pw KC_DB_PASSWORD
SELECT 'CREATE ROLE keycloak LOGIN' WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='keycloak') \gexec
ALTER ROLE keycloak PASSWORD :'pw';
SELECT 'CREATE DATABASE keycloak OWNER keycloak' WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname='keycloak') \gexec
SQL
      # Mailpit (P1-T5c) catches Keycloak's setup e-mails; nothing leaves this machine.
      "${COMPOSE[@]}" --profile keycloak up -d --wait keycloak mailpit
      kc_manage ihr_keycloak_sync --realm --all
      # The two workers (P1-T5f) each get only their own narrow service-account secret, in a
      # file of their own; never the bootstrap admin credential.
      write_worker_env onboarding provisioner.env IHR_KEYCLOAK_ONBOARDING_SECRET
      write_worker_env staff staff-worker.env IHR_KEYCLOAK_STAFF_SECRET
      "${COMPOSE[@]}" --profile keycloak up -d --force-recreate provisioner staff-worker
      echo "Operator console: http://console.localhost:9000/ops/ (first time: scripts/care-dev.sh keycloak seed)"
      echo "Keycloak: http://auth.localhost:8081 (next, first time: scripts/care-dev.sh keycloak seed)"
      echo "E-mail inbox (setup links): http://127.0.0.1:8025"
      ;;
    sync) kc_manage ihr_keycloak_sync "${@:2}" ;;
    seed)
      # Synthetic staff with fresh passwords and TOTP secrets; written to TEST_USERS.md
      local json
      json="$(kc_manage ihr_keycloak_demo_users | tail -1)"
      python3 "$ROOT/scripts/keycloak_test_users.py" "$ROOT/deploy/seed/TEST_USERS.md" <<<"$json"
      echo "Keycloak test logins added to deploy/seed/TEST_USERS.md"
      ;;
    otp)
      # Current 6-digit code for a demo user (reads the secret from TEST_USERS.md)
      python3 "$ROOT/scripts/keycloak_test_users.py" --otp "${2:?user}" "$ROOT/deploy/seed/TEST_USERS.md"
      ;;
    devtools)
      docker rm -f indiehr-kc-devtools >/dev/null 2>&1 || true
      docker run -d --rm --name indiehr-kc-devtools --memory 48m -p 127.0.0.1:8082:8082 \
        -v "$ROOT/deploy/keycloak/devtools:/srv:ro" --entrypoint python care_local \
        -m http.server -d /srv 8082 >/dev/null
      for slug in "${HOSPITALS[@]}"; do echo "Token viewer: http://$slug.localhost:8082/"; done
      ;;
    logs) "${COMPOSE[@]}" --profile keycloak logs --tail=100 keycloak provisioner staff-worker mailpit ;;
    stop) "${COMPOSE[@]}" --profile keycloak stop provisioner staff-worker keycloak mailpit; docker rm -f indiehr-kc-devtools >/dev/null 2>&1 || true ;;
    *) echo "scripts/care-dev.sh keycloak <up|seed|otp USER|devtools|sync [--check|--rebuild-flows]|logs|stop>"; exit 1 ;;
  esac
}

# Audit fingerprints (P1-T6b, ADR-010): a write-once bucket in the dev MinIO and two narrow
# accounts, one that may only add objects (Celery's hourly job) and one that may only read
# (verify, export). Dev uses GOVERNANCE retention for 30 days so the bucket can be cleaned up;
# production uses COMPLIANCE for 10 years (P1-T8).
ANCHOR_BUCKET=ihr-audit-anchors
audit_anchors() {
  local dir="$ROOT/deploy/dev" wkey rkey wsecret rsecret
  wkey=ihr-anchor-writer; rkey=ihr-anchor-reader
  wsecret="$(python3 -c 'import secrets;print(secrets.token_hex(20))')"
  rsecret="$(python3 -c 'import secrets;print(secrets.token_hex(20))')"
  local mc=("${COMPOSE[@]}" exec -T minio mc)
  "${mc[@]}" mb --ignore-existing --with-lock "local/$ANCHOR_BUCKET"
  "${mc[@]}" retention set --default GOVERNANCE 30d "local/$ANCHOR_BUCKET"
  "${COMPOSE[@]}" exec -T minio sh -c 'cat > /tmp/ihr-anchor-write.json' <<EOT
{"Version":"2012-10-17","Statement":[{"Effect":"Allow","Action":["s3:PutObject"],"Resource":["arn:aws:s3:::$ANCHOR_BUCKET/anchors/*"]}]}
EOT
  "${COMPOSE[@]}" exec -T minio sh -c 'cat > /tmp/ihr-anchor-read.json' <<EOT
{"Version":"2012-10-17","Statement":[{"Effect":"Allow","Action":["s3:GetObject","s3:GetObjectVersion"],"Resource":["arn:aws:s3:::$ANCHOR_BUCKET/anchors/*"]},{"Effect":"Allow","Action":["s3:ListBucket","s3:ListBucketVersions","s3:GetBucketObjectLockConfiguration","s3:GetBucketVersioning"],"Resource":["arn:aws:s3:::$ANCHOR_BUCKET"]}]}
EOT
  "${mc[@]}" admin policy create local ihr-anchor-write /tmp/ihr-anchor-write.json
  "${mc[@]}" admin policy create local ihr-anchor-read /tmp/ihr-anchor-read.json
  "${mc[@]}" admin user add local "$wkey" "$wsecret" >/dev/null
  "${mc[@]}" admin user add local "$rkey" "$rsecret" >/dev/null
  "${mc[@]}" admin policy attach local ihr-anchor-write --user "$wkey" >/dev/null 2>&1 || true
  "${mc[@]}" admin policy attach local ihr-anchor-read --user "$rkey" >/dev/null 2>&1 || true
  local common="IHR_AUDIT_ANCHOR_ENDPOINT=http://minio:9000
IHR_AUDIT_ANCHOR_BUCKET=$ANCHOR_BUCKET"
  (umask 077
   printf '# Audit fingerprint writer (P1-T6b), written by scripts/care-dev.sh. Never commit.\n%s\nIHR_AUDIT_ANCHOR_WRITE_KEY=%s\nIHR_AUDIT_ANCHOR_WRITE_SECRET=%s\n' \
     "$common" "$wkey" "$wsecret" > "$dir/audit-anchor-write.env"
   printf '# Audit fingerprint reader (P1-T6b), written by scripts/care-dev.sh. Never commit.\n%s\nIHR_AUDIT_ANCHOR_READ_KEY=%s\nIHR_AUDIT_ANCHOR_READ_SECRET=%s\n' \
     "$common" "$rkey" "$rsecret" > "$dir/audit-anchor-read.env")
  "${COMPOSE[@]}" up -d --wait backend celery
  "${COMPOSE[@]}" exec -T backend python manage.py ihr_audit_verify --all --seal 2>&1 | tail -3 || true
  echo "Fingerprint bucket ready; the first one is written within the hour (or: verify --anchor)."
}

case "${1:-}" in
  up)
    # Rebuild the dev image whenever its inputs (lock file, Dockerfile) change
    WANT="$(cat "$BACKEND/Pipfile.lock" "$BACKEND/docker/dev.Dockerfile" | sha256sum | cut -c1-16)"
    HAVE="$(docker image inspect care_local --format '{{ index .Config.Labels "indiehr.deps" }}' 2>/dev/null || true)"
    if [[ "$WANT" != "$HAVE" ]]; then
      echo "Building care_local (dependency hash $WANT, image has '${HAVE:-none}')"
      docker buildx build --load --label "indiehr.deps=$WANT" \
        -f "$BACKEND/docker/dev.Dockerfile" -t care_local "$BACKEND"
    fi
    # The tenant-mode database is created once; migrations run when the celery container starts.
    "${COMPOSE[@]}" up -d --wait db
    if [[ -z "$("${COMPOSE[@]}" exec -T db psql -U postgres -tAc "SELECT 1 FROM pg_database WHERE datname='$DB'")" ]]; then
      "${COMPOSE[@]}" exec -T db psql -U postgres -qc "CREATE DATABASE $DB"
    fi
    "${COMPOSE[@]}" up -d --wait
    echo "API is up. Next: scripts/care-dev.sh seed (first time), then scripts/care-dev.sh frontend"
    ;;
  down) "${COMPOSE[@]}" --profile keycloak down; docker rm -f indiehr-frontend indiehr-kc-devtools >/dev/null 2>&1 || true ;;
  ps) "${COMPOSE[@]}" --profile keycloak ps; docker ps --filter name=indiehr-frontend --format '{{.Names}} {{.Status}} {{.Ports}}' ;;
  logs) "${COMPOSE[@]}" logs --tail=100 "${@:2}" ;;
  seed)
    # Two synthetic hospitals with CARE's demo data, and fresh passwords per hospital (P0-T11)
    entries=()
    for slug in "${HOSPITALS[@]}"; do entries+=("$(seed_hospital "$slug")"); done
    write_test_users "${entries[@]}"
    echo "Test logins written to deploy/seed/TEST_USERS.md"
    ;;
  reset-passwords)
    entries=()
    for slug in "${HOSPITALS[@]}"; do entries+=("$(seed_hospital "$slug" --passwords-only)"); done
    write_test_users "${entries[@]}"
    echo "New passwords written to deploy/seed/TEST_USERS.md"
    ;;
  shell) "${COMPOSE[@]}" exec backend bash ;;
  frontend)
    # Serve a pre-built bundle (from CI artifact) unpacked into deploy/dev/frontend-build
    BUILD="$ROOT/deploy/dev/frontend-build"
    test -f "$BUILD/index.html" || { echo "No bundle in $BUILD (see docs/LOCAL_DEV.md)"; exit 1; }
    "$ROOT/scripts/check-bundle-egress.sh" "$BUILD"
    docker buildx build -q --load -f "$ROOT/deploy/docker/frontend.Dockerfile" \
      --build-context config="$ROOT/deploy/docker" -t "$FE_IMAGE" "$BUILD" >/dev/null
    docker rm -f indiehr-frontend >/dev/null 2>&1 || true
    # Same-origin API: nginx passes each hospital's host through to the backend.
    docker run -d --name indiehr-frontend -p 127.0.0.1:8080:8080 --memory 64m \
      --network care -e API_UPSTREAM=http://backend:9000 \
      -e CSP_STORAGE_ORIGIN=http://localhost:9100 \
      "$FE_IMAGE" >/dev/null
    for slug in "${HOSPITALS[@]}"; do echo "Web app: http://$slug.localhost:8080"; done
    ;;
  keycloak) keycloak_cmd "${@:2}" ;;
  audit-anchors) audit_anchors ;;
  provision) kc_manage ihr_provision "${@:2}" ;;
  provision-demo)
    # A synthetic hospital brought live by the provisioning engine (P1-T5a). Its first admin's
    # setup e-mail (P1-T5c) is replaced by a ready-made dev login for scripted demos.
    slug="${2:?slug, e.g. gamma}"
    time kc_manage ihr_provision start --slug "$slug" --name "${slug^} Health Pvt Ltd" \
      --display-name "${slug^} Test Hospital" --state-code 27 --district Pune --city Pune \
      --pin-code 411001 --phone +912000000099 --address "1 Test Road, Pune" \
      --facility-name "${slug^} Test Hospital" --admin-email "admin@$slug.example.test" \
      --admin-first-name Test --admin-last-name Admin
    json="$(kc_manage ihr_provision dev-activate-admin --slug "$slug" | tail -1)"
    python3 "$ROOT/scripts/keycloak_test_users.py" --provisioned "$ROOT/deploy/seed/TEST_USERS.md" <<<"$json"
    echo "Sign in: http://$slug.localhost:8080/api/ihr/auth/login/?next=/api/ihr/auth/session/ (login in deploy/seed/TEST_USERS.md)"
    ;;
  *) sed -n '3,4p' "$0"; exit 1 ;;
esac

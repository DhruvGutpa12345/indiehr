mkdir -p "$ROOT/deploy/dev/client-keys"

# Object storage keys (P1-T8b3): one file for the SeaweedFS gateway (every identity), and from
# it the keys each container gets: CARE's patient files and pictures (one key each, P1-T20b),
# the fingerprint writer (Celery), the fingerprint reader (backend). Generated once,
# git-ignored, owner-only.
S3_ENV="$ROOT/deploy/dev/s3-gateway.env"
# The combined CARE key P1-T20b retired, kept only so `s3-check` can prove it dead
S3_RETIRED="$ROOT/deploy/dev/s3-retired.env"
ANCHOR_BUCKET=ihr-audit-anchors
s3_after_split() {  # C2: the split runs on whatever command comes first after the pull, so the
  # running gateway learns the new keys (and forgets the old) at once, and the running containers
  # that hold CARE's keys move with it; never a backend on keys the gateway does not know. A
  # running backend or celery with the gateway stopped holds the retired key too: the gateway is
  # started for them. Then the buckets are set up again, so the pictures bucket loses its old
  # public-read policy now, not at the next `up` (the second fixer's review)
  local svc moved=()
  for svc in celery backend; do
    [[ -z "$("${COMPOSE[@]}" ps -q "$svc" 2>/dev/null || true)" ]] || moved+=("$svc")
  done
  [[ -n "$("${COMPOSE[@]}" ps -q s3 2>/dev/null || true)" ]] || ((${#moved[@]})) || return 0
  "${COMPOSE[@]}" up -d --wait --no-deps --force-recreate s3 >&2
  if ((${#moved[@]})); then "${COMPOSE[@]}" up -d --wait --no-deps --force-recreate "${moved[@]}" >&2; fi
  s3_buckets >&2 || die "Object storage: the keys are split and the containers moved, but setting up the buckets failed (above), so the pictures bucket may still be public-read: run scripts/care-dev.sh up"
  echo "Object storage: s3 recreated with the split keys${moved[*]:+, then ${moved[*]}}; buckets set up again (pictures private)" >&2
}
s3_secrets() {
  local k split=0
  hex() { python3 -c "import secrets;print(secrets.token_hex($1))"; }
  if [[ ! -f "$S3_ENV" ]]; then
    (umask 077; {
      echo "# Local SeaweedFS keys (P1-T8b3), generated by scripts/care-dev.sh. Never commit."
      for k in ADMIN FILES PICTURES ANCHOR_WRITE ANCHOR_READ BACKUP LOGS_ARCHIVE; do
        echo "IHR_S3_${k}_KEY=ihr$(hex 10)"
        echo "IHR_S3_${k}_SECRET=$(hex 20)"
      done
    } > "$S3_ENV")
  fi
  # Added in P1-T8c (the backup identity): older key files get it once
  if ! grep -q '^IHR_S3_BACKUP_KEY=' "$S3_ENV"; then
    (umask 077; printf 'IHR_S3_BACKUP_KEY=ihr%s\nIHR_S3_BACKUP_SECRET=%s\n' "$(hex 10)" "$(hex 20)" >> "$S3_ENV")
  fi
  # Added in P1-T9c (the log archive's identity; the shared start.sh needs it): the same, once
  if ! grep -q '^IHR_S3_LOGS_ARCHIVE_KEY=' "$S3_ENV"; then
    (umask 077; printf 'IHR_S3_LOGS_ARCHIVE_KEY=ihr%s\nIHR_S3_LOGS_ARCHIVE_SECRET=%s\n' "$(hex 10)" "$(hex 20)" >> "$S3_ENV")
  fi
  # P1-T20b: CARE's one key for both buckets (identity ihr-care) becomes two, ihr-care-files and
  # ihr-care-pictures. Older key files are moved once: new keys added, the old one taken out of
  # the gateway's file (so the gateway forgets it) and kept aside for the live check
  if ! grep -q '^IHR_S3_FILES_KEY=' "$S3_ENV"; then
    (umask 077
     if grep -q '^IHR_S3_CARE_KEY=' "$S3_ENV"; then
       { echo "# The combined CARE key retired by P1-T20b (dead: s3-check proves it). Never commit."
         sed -n 's/^IHR_S3_CARE_\(KEY\|SECRET\)=/IHR_S3_RETIRED_CARE_\1=/p' "$S3_ENV"; } > "$S3_RETIRED"
     fi
     { grep -v '^IHR_S3_CARE_\(KEY\|SECRET\)=' "$S3_ENV"
       printf 'IHR_S3_FILES_KEY=ihr%s\nIHR_S3_FILES_SECRET=%s\n' "$(hex 10)" "$(hex 20)"
       printf 'IHR_S3_PICTURES_KEY=ihr%s\nIHR_S3_PICTURES_SECRET=%s\n' "$(hex 10)" "$(hex 20)"
     } > "$S3_ENV.new"
     mv "$S3_ENV.new" "$S3_ENV")
    echo "Object storage: CARE's key split into a patient files key and a pictures key (P1-T20b)" >&2
    split=1
  fi
  s3v() { sed -n "s/^IHR_S3_$1=//p" "$S3_ENV"; }
  local common="IHR_AUDIT_ANCHOR_ENDPOINT=http://s3:8333
IHR_AUDIT_ANCHOR_BUCKET=$ANCHOR_BUCKET"
  (umask 077
   printf '# CARE: patient files and pictures, one key each (P1-T20b), from s3-gateway.env by scripts/care-dev.sh. Never commit.\nFILE_UPLOAD_KEY=%s\nFILE_UPLOAD_SECRET=%s\nFACILITY_S3_KEY=%s\nFACILITY_S3_SECRET=%s\n' \
     "$(s3v FILES_KEY)" "$(s3v FILES_SECRET)" "$(s3v PICTURES_KEY)" "$(s3v PICTURES_SECRET)" > "$ROOT/deploy/dev/s3-care.env"
   printf '# Audit fingerprint writer (P1-T6b), from s3-gateway.env by scripts/care-dev.sh. Never commit.\n%s\nIHR_AUDIT_ANCHOR_WRITE_KEY=%s\nIHR_AUDIT_ANCHOR_WRITE_SECRET=%s\n' \
     "$common" "$(s3v ANCHOR_WRITE_KEY)" "$(s3v ANCHOR_WRITE_SECRET)" > "$ROOT/deploy/dev/audit-anchor-write.env"
   printf '# Audit fingerprint reader (P1-T6b), from s3-gateway.env by scripts/care-dev.sh. Never commit.\n%s\nIHR_AUDIT_ANCHOR_READ_KEY=%s\nIHR_AUDIT_ANCHOR_READ_SECRET=%s\n' \
     "$common" "$(s3v ANCHOR_READ_KEY)" "$(s3v ANCHOR_READ_SECRET)" > "$ROOT/deploy/dev/audit-anchor-read.env")
  # After the derived files: the recreated containers read the new keys
  if ((split)); then s3_after_split; fi
}

s3_tool() {  # s3_tool <script> <args>: a deploy/s3 script in the dev backend image (boto3), with
  # the S3_* keys mapped from s3-gateway.env through the environment (never on a command line)
  local script="$1" k v envs=()
  shift
  for k in ADMIN FILES PICTURES ANCHOR_WRITE ANCHOR_READ; do
    for v in KEY SECRET; do
      export "S3_${k}_${v}=$(sed -n "s/^IHR_S3_${k}_${v}=//p" "$S3_ENV")"
      envs+=(-e "S3_${k}_${v}")
    done
  done
  if [[ -f "$S3_RETIRED" ]]; then  # the retired combined key: s3-check proves it dead
    for v in KEY SECRET; do
      export "S3_RETIRED_CARE_${v}=$(sed -n "s/^IHR_S3_RETIRED_CARE_${v}=//p" "$S3_RETIRED")"
      envs+=(-e "S3_RETIRED_CARE_${v}")
    done
  fi
  "${COMPOSE[@]}" run --rm --no-deps -T "${envs[@]}" -v "$ROOT/deploy/s3:/ihr-s3:ro" \
    --entrypoint python backend "/ihr-s3/$script" --endpoint http://s3:8333 \
    --patient patient-bucket --facility facility-bucket --anchor "$ANCHOR_BUCKET" "$@"
}


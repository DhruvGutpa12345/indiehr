    if [[ -n "$kc" ]]; then printf '\n%s\n' "$kc"; fi
  } > "$ROOT/deploy/seed/TEST_USERS.md"
  chmod 600 "$ROOT/deploy/seed/TEST_USERS.md"
}

# Run a Keycloak management command in the backend container. The admin secret is passed by
# name only (-e VAR), so it never shows in the host's process list, and it is never part of the
# backend's own environment.
kc_manage() {
  set -a
  # shellcheck disable=SC1090,SC1091
  source "$KC_ENV"
  set +a
  IHR_KEYCLOAK_ADMIN_CLIENT_ID="$KC_BOOTSTRAP_ADMIN_CLIENT_ID" \
  IHR_KEYCLOAK_ADMIN_CLIENT_SECRET="$KC_BOOTSTRAP_ADMIN_CLIENT_SECRET" \
    "${COMPOSE[@]}" exec -T -e IHR_KEYCLOAK_ADMIN_CLIENT_ID -e IHR_KEYCLOAK_ADMIN_CLIENT_SECRET \
    backend python manage.py "$@"
}


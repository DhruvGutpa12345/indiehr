@unittest.skipUnless(STAGING.exists(), "scripts/staging.sh is not here (the dumper image's run)")
class Wiring(unittest.TestCase):
    """scripts/staging.sh's restore keeps the live system out of the quarantine and the drill."""

    @classmethod
    def setUpClass(cls):
        import re

        cls.text = STAGING.read_text()

        def func(name):
            m = re.search(r"^%s\(\) \{(.*?)^\}" % re.escape(name), cls.text, re.S | re.M)
            assert m, name
            return m.group(1)

        cls.func = staticmethod(func)

    def test_the_quarantine_has_no_network_and_a_read_only_root(self):
        body = self.func("restore_quarantine")
        for flag in ("--network none", "--read-only", "--user 70:70", "--cap-drop ALL",
                     "no-new-privileges:true", '-v "$work/in:/in:ro"'):
            self.assertIn(flag, body)
        self.assertNotIn("--env-file", body)  # no key of any kind

    def test_the_drill_never_gets_live_settings_or_networks(self):
        body = self.func("hospital_restore_drill")

def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class Static(unittest.TestCase):
    """Without Postgres: the manifest's cross-check and the statement forms."""

    @classmethod
    def setUpClass(cls):
        cls.q = _load("quarantine", QUARANTINE)
        cls.p = _load("package", PACKAGE)

    def facts(self):
        return {"migrations": [["emr", "0001_initial"], ["ihr_audit", "0001_initial"]],
                "audit": {"seal_seq": 4, "seal_hash": "ab" * 32}}

    def manifest(self, **over):
        import hashlib

        rows = "\n".join(sorted(["emr.0001_initial", "ihr_audit.0001_initial"]))
        m = {"schema": SCHEMA, "audit": {"seal_seq": 4, "seal_hash": "ab" * 32},
             "sequences": {"users_user_id_seq": 50, "never_used_seq": None},
             "migrations_sha256": hashlib.sha256(rows.encode()).hexdigest(), **over}
        return {"authentic": True, "manifest": m}

    def test_a_matching_manifest(self):
        seqs = {"users_user_id_seq": [50, True], "never_used_seq": [1, False]}
        self.assertEqual(self.q.manifest_problems(self.manifest(), SCHEMA, self.facts(), seqs), [])

    def test_each_mismatch_is_named(self):
        seqs = {"users_user_id_seq": [50, True]}
        for over, text in (({"schema": "h_other00001"}, "another schema"),
                           ({"audit": {"seal_seq": 3, "seal_hash": "ab" * 32}}, "audit head"),
                           ({"sequences": {"users_user_id_seq": 49}}, "sequence values"),
                           ({"migrations_sha256": "0" * 64}, "migrations")):
            problems = self.q.manifest_problems(self.manifest(**over), SCHEMA, self.facts(), seqs)
            self.assertTrue(any(text in p for p in problems), (over, problems))
        unsigned = self.manifest()
        unsigned["authentic"] = False
        self.assertTrue(self.q.manifest_problems(unsigned, SCHEMA, self.facts(), seqs))

    def test_statement_forms(self):
        good = (("table", f'CREATE TABLE "{SCHEMA}"."t" (x int)'),
                ("index", f"CREATE INDEX i ON {SCHEMA}.t USING btree (x)"),
                ("constraint", f'ALTER TABLE ONLY "{SCHEMA}"."t" ADD CONSTRAINT "f" FOREIGN KEY (x) REFERENCES {SCHEMA}.u(id)'))
        for phase, text in good:
            self.p._check_statement(phase, text, SCHEMA)
        bad = (("table", 'CREATE TABLE "h_other00001"."t" (x int)'),
               ("index", f"CREATE FUNCTION {SCHEMA}.f() RETURNS int"),
               ("constraint", f'ALTER TABLE ONLY "{SCHEMA}"."t" ADD CONSTRAINT "f" FOREIGN KEY (x) REFERENCES public.u(id)'),
               ("owned", f'ALTER SEQUENCE "{SCHEMA}"."s" OWNED BY "h_other00001"."t"."x"'))
        for phase, text in bad:
            with self.assertRaises(self.p.PackageError, msg=text):
                self.p._check_statement(phase, text, SCHEMA)

    def test_a_statement_is_matched_whole(self):
        """Review S2: anything after a statement of a known form (a second statement, a
        comment, INHERITS) is refused; a ";" inside a literal or a quoted name is not one."""
        q = f'"{SCHEMA}"."t"'
        bad = (("table", f"CREATE TABLE {q} (x int); DROP SCHEMA h_other00001 CASCADE; --"),
               ("table", f"CREATE TABLE {q} (x int) INHERITS (h_other00001.users_user)"),
               ("table", f"CREATE TABLE {q} (x int) PARTITION BY RANGE (x)"),
               ("index", f"CREATE INDEX i ON {SCHEMA}.t USING btree (x); SELECT 1"),
               ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "c" CHECK ((x > 0)) -- )'),
               ("constraint", f"ALTER TABLE ONLY {q} ADD CONSTRAINT \"c\" CHECK ((x > 0)) $$; SELECT 1"),
               ("sequence", f'CREATE SEQUENCE "{SCHEMA}"."s" AS bigint START WITH 1 INCREMENT BY 1 '
                            "MINVALUE 1 MAXVALUE 9 CACHE 1 NO CYCLE OWNED BY h_other00001.t.x"),
               ("owned", f'ALTER SEQUENCE "{SCHEMA}"."s" OWNED BY {q}."x"; SELECT 1'),
               # one constraint and another ALTER TABLE subcommand after it (review S2, after the
               # second verification): a USING runs for every row and is never stored
               ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "p" PRIMARY KEY (id), ALTER COLUMN "x" '
                              "TYPE text USING (pg_catalog.query_to_xml('select 1', true, false, '')::text)"),
               ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "p" PRIMARY KEY (id), OWNER TO ihr_app'),
               ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "u" UNIQUE (x), DISABLE TRIGGER ALL'),
               ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "f" FOREIGN KEY (x) REFERENCES {q}(id) '
                              'DEFERRABLE INITIALLY DEFERRED, ADD CONSTRAINT "g" FOREIGN KEY (y) REFERENCES public.u(id)'),
               ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "c" CHECK ((x > 0)), ALTER COLUMN y TYPE int USING (1)'),
               ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "p" PRIMARY KEY ((id))'),
               ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "p" PRIMARY KEY (id) ALTER COLUMN x SET DEFAULT 1'))
        for phase, text in bad:
            with self.assertRaises(self.p.PackageError, msg=text):
                self.p._check_statement(phase, text, SCHEMA)
        good = (("table", f"CREATE TABLE {q} (x text DEFAULT 'a;b' NOT NULL, \"y;z\" varchar(10)) WITH (fillfactor=90)"),
                ("constraint", f"ALTER TABLE ONLY {q} ADD CONSTRAINT \"c\" CHECK ((x <> E'\\';'::text))"),
                ("constraint", f"ALTER TABLE ONLY {q} ADD CONSTRAINT \"c\" CHECK ((x <> ', OWNER TO x'::text)) NO INHERIT"),
                ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "u" UNIQUE NULLS NOT DISTINCT (a, b) INCLUDE (c) '
                               "WITH (fillfactor=90) DEFERRABLE INITIALLY DEFERRED"),
                ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "f" FOREIGN KEY (a, b) REFERENCES {q}(id, k) '
                               "MATCH FULL ON UPDATE CASCADE ON DELETE SET NULL (a) NOT VALID"),
                ("constraint", f'ALTER TABLE ONLY {q} ADD CONSTRAINT "x" EXCLUDE USING gist (c WITH &&) WHERE ((x > 0))'))
        for phase, text in good:
            self.p._check_statement(phase, text, SCHEMA)

    def test_what_is_built_before_the_rows(self):
        """Review S1: CHECKs (as NOT VALID, validated after the rows), exclusion constraints
        and indexes with an expression or a predicate are made on the empty tables and
        inspected first; keys, plain indexes and foreign keys after the rows."""
        q = f'"{SCHEMA}"."t"'
        when = {
            f"ALTER TABLE ONLY {q} ADD CONSTRAINT \"c\" CHECK ((x > 0))": "early",
            f"ALTER TABLE ONLY {q} ADD CONSTRAINT \"p\" PRIMARY KEY (id)": "late",
            f"ALTER TABLE ONLY {q} ADD CONSTRAINT \"f\" FOREIGN KEY (u) REFERENCES {q}(id)": "late",
            f"CREATE INDEX i ON {SCHEMA}.t USING btree (x)": "late",
            f"CREATE UNIQUE INDEX i ON {SCHEMA}.t USING btree (x, \"Y\" DESC NULLS LAST) INCLUDE (z)": "late",
            # an operator class named: early (its functions run for every row: inspected first)
            f"CREATE INDEX i ON {SCHEMA}.t USING gin (username public.gin_trgm_ops)": "early",
            f"CREATE INDEX i ON {SCHEMA}.t USING btree (name varchar_pattern_ops)": "early",
            f"CREATE INDEX i ON {SCHEMA}.t USING btree (upper(x))": "early",
            f"CREATE INDEX i ON {SCHEMA}.t USING btree (x) WHERE (y IS NOT NULL)": "early",
        }
        for text, expected in when.items():
            got, statement, validate = self.p._post(text, SCHEMA)
            self.assertEqual(got, expected, text)
            if "CHECK" in text:
                self.assertTrue(statement.endswith(" NOT VALID"))
                self.assertEqual(validate, (q, '"c"'))
        already = f"ALTER TABLE ONLY {q} ADD CONSTRAINT \"c\" CHECK ((x > 0)) NOT VALID"
        self.assertEqual(self.p._post(already, SCHEMA), ("early", already, None))



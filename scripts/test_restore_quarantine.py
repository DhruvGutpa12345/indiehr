@unittest.skipUnless(LIVE, "needs Postgres's programs and psycopg: scripts/test-dumps-live.sh")
class Live(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        import psycopg

        cls.psycopg = psycopg
        cls.q = _load("quarantine", QUARANTINE)
        cls.p = _load("package", PACKAGE)
        cls.tmp = tempfile.mkdtemp(prefix="quarantine-test-")
        cls.data = os.path.join(cls.tmp, "data")
        cls.env = {**os.environ, "PGHOST": cls.tmp, "PGUSER": "postgres"}
        subprocess.run(["initdb", "-D", cls.data, "-U", "postgres", "--auth=trust", "--no-sync"],
                       check=True, capture_output=True)
        subprocess.run(["pg_ctl", "-D", cls.data, "-w", "-l", os.path.join(cls.tmp, "log"), "-o",
                        f"-c listen_addresses='' -c unix_socket_directories={cls.tmp} -c fsync=off", "start"],
                       check=True, capture_output=True, env=cls.env)
        cls.plan = os.path.join(cls.tmp, "plan.json")
        Path(cls.plan).write_text(json.dumps({"schema": SCHEMA, "extensions": ["pg_trgm"]}))

    @classmethod
    def tearDownClass(cls):
        subprocess.run(["pg_ctl", "-D", cls.data, "-m", "immediate", "-w", "stop"], capture_output=True, env=cls.env)
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def psql(self, db, text):
        r = subprocess.run(["psql", "-X", "-v", "ON_ERROR_STOP=1", "-q", "-d", db, "-c", text],
                           capture_output=True, env=self.env)
        if r.returncode:
            raise AssertionError(f"psql: {r.stderr.decode()[-500:]}")

    def source(self, name, extra="", dump_args=()):
        """A database holding the hospital schema (plus ``extra``), dumped as the dumper does."""
        self.psql("postgres", f"CREATE DATABASE {name}")
        self.psql(name, SETUP)
        if extra:  # a transaction of its own (the deferred foreign key's checks are done)
            self.psql(name, extra)
        dump = os.path.join(self.tmp, f"{name}.dump")
        subprocess.run(["pg_dump", "-Fc", "-n", SCHEMA, *dump_args, "--no-owner", "--no-acl", "-f", dump, name],
                       check=True, capture_output=True, env=self.env)
        return dump

    def quarantine(self, dump, out, manifest=None):
        args = ["--dump", dump, "--plan", self.plan, "--out", out, "--work", self.tmp]
        if manifest:
            path = os.path.join(self.tmp, "manifest.json")
            Path(path).write_text(json.dumps(manifest))
            args += ["--manifest", path]
        else:
            args += ["--pitr", "2026-11-14T10:00:00+05:30"]
        return self.q.main(args)

    def test_a_clean_dump_becomes_a_package_that_loads_the_same(self):
        dump = self.source("clean")
        out = os.path.join(self.tmp, "clean-package")
        self.assertEqual(self.quarantine(dump, out), 0)
        doc = json.loads(Path(out, "package.json").read_text())
        self.assertEqual(doc["report"]["quarantine"], "passed")
        self.assertEqual(sorted(doc["functions"]), ["ihr_audit_refuse", "ihr_audit_row"])
        ddl = Path(out, "ddl.json").read_text()
        self.assertNotIn("FUNCTION", ddl)
        self.assertNotIn("TRIGGER", ddl)
        self.psql("postgres", "CREATE DATABASE live")
        self.psql("live", "CREATE EXTENSION pg_trgm")
        with self.psycopg.connect(f"postgresql://postgres@/live?host={self.tmp}") as conn:
            with conn.transaction():
                result = self.p.load(conn, out, SCHEMA)
            cur = conn.cursor()
            self.assertEqual(result["rows"], 2 + 50 + 120 + 2 + 1)
            cur.execute(f"SELECT count(*), sum(length(note)) FROM {SCHEMA}.users_user")
            self.assertEqual(cur.fetchone()[0], 50)
            cur.execute(f"SELECT nextval('{SCHEMA}.emr_thing_id_seq')")
            self.assertEqual(cur.fetchone()[0], 121)
            cur.execute(f"SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace WHERE nspname = '{SCHEMA}'")
            self.assertEqual(cur.fetchone()[0], 0)  # the live side installs its own from code
        # the source and the loaded copy have the same shape
        with self.psycopg.connect(f"postgresql://postgres@/clean?host={self.tmp}") as conn:
            src = self.p.shape(conn.cursor(), SCHEMA)[0]
        self.assertEqual(src, doc["shape"])

    def test_each_attack_is_refused_with_no_package(self):
        for n, (what, sql) in enumerate(sorted(ATTACKS.items())):
            with self.subTest(what):
                dump = self.source(f"attack{n}", sql)
                out = os.path.join(self.tmp, f"attack{n}-package")
                self.assertEqual(self.quarantine(dump, out), 1, what)
                self.assertFalse(Path(out, "package.json").exists(), what)

    def test_a_second_schema_or_an_extension_in_the_dump_is_refused(self):
        dump = self.source("twoschemas", "CREATE SCHEMA h_another001; CREATE TABLE h_another001.t (x int);",
                           dump_args=("-n", "h_another001"))
        self.assertEqual(self.quarantine(dump, os.path.join(self.tmp, "two-package")), 1)
        dump = self.source("withext", "", dump_args=("-e", "pg_trgm"))
        self.assertEqual(self.quarantine(dump, os.path.join(self.tmp, "ext-package")), 1)

    def test_a_forged_check_in_the_package_never_runs(self):
        """Review S1/S2, against a real server: a package whose CHECK would reset another
        schema's sequence is refused by the load before any row meets that CHECK (setval
        would not be undone by the roll-back), and the sequence keeps its value."""
        dump = self.source("forged")
        out = os.path.join(self.tmp, "forged-package")
        self.assertEqual(self.quarantine(dump, out), 0)
        ddl = json.loads(Path(out, "ddl.json").read_text())
        victim = "pg_catalog.setval('victim.s'::regclass, (1)::bigint)"
        ddl["post"] = [t.replace("CHECK ((note <> ''::text))", f"CHECK (((note <> ''::text) OR ({victim} > 0)))")
                       for t in ddl["post"]]
        self.assertIn(victim, json.dumps(ddl))
        Path(out, "ddl.json").write_text(json.dumps(ddl))
        doc = json.loads(Path(out, "package.json").read_text())
        doc["ddl_sha256"] = self.p._sha(Path(out, "ddl.json"))
        Path(out, "package.json").write_text(json.dumps(doc))
        self.psql("postgres", "CREATE DATABASE forgedlive")
        self.psql("forgedlive", "CREATE EXTENSION pg_trgm; CREATE SCHEMA victim; CREATE SEQUENCE victim.s; "
                                "SELECT setval('victim.s', 5)")
        with self.psycopg.connect(f"postgresql://postgres@/forgedlive?host={self.tmp}") as conn:
            with self.assertRaisesRegex(self.p.PackageError, "setval"), conn.transaction():
                self.p.load(conn, out, SCHEMA)
            self.assertEqual(conn.execute("SELECT last_value FROM victim.s").fetchone()[0], 5)

    def test_the_package_hash_is_printed_once_the_server_is_stopped(self):
        import contextlib
        import hashlib
        import io

        dump = self.source("hashed")
        out = os.path.join(self.tmp, "hashed-package")
        printed = io.StringIO()
        with contextlib.redirect_stdout(printed):
            self.assertEqual(self.quarantine(dump, out), 0)
        lines = [x for x in printed.getvalue().splitlines() if x.startswith("quarantine: package sha256 ")]
        self.assertEqual(len(lines), 1)
        self.assertEqual(lines[0].rsplit(" ", 1)[1], hashlib.sha256(Path(out, "package.json").read_bytes()).hexdigest())
        self.assertEqual(self.p.recheck(out, {"package.json": lines[0].rsplit(" ", 1)[1]}), [])
        Path(out, "package.json").write_text(Path(out, "package.json").read_text() + " ")
        self.assertTrue(self.p.recheck(out, {"package.json": lines[0].rsplit(" ", 1)[1]}))

    def test_a_manifest_that_does_not_match_is_refused(self):
        dump = self.source("manifested")
        bad = {"authentic": True, "manifest": {"schema": SCHEMA, "audit": {"seal_seq": 9, "seal_hash": "00" * 32},
                                               "snapshot": {"at": "2026-11-14T03:30:00+05:30"}}}
        self.assertEqual(self.quarantine(dump, os.path.join(self.tmp, "manifested-package"), bad), 1)



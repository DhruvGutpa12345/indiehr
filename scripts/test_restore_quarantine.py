"""The quarantine of a hospital's dump and the package it writes (P1-T22b; design "After the
attack" 8): deploy/restore/quarantine.py and plugins/ihr_platform/ihr_platform/restore/package.py.

The class Live runs only where Postgres's programs and psycopg are (the dumper image):
scripts/test-dumps-live.sh runs this file there too. It builds a hospital-shaped schema in a
throwaway server, dumps it with pg_dump, puts the dump through the quarantine, loads the package
into another database and compares; then dumps that try something else (a function or trigger not
ours, a view, a second schema, an extension, a call into public, a built-in with an effect beyond
the row in a default or a CHECK, a manifest that does not match) are each refused, with no package
written; a forged package's CHECK is refused by the load before it can run.

Run: python3 -m unittest scripts/test_restore_quarantine.py (static part anywhere).
"""

